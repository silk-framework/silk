export const APP_VIEWHEADER_ID = "diapp__viewheader";

// Header element that uses portal function to get rendered in one special place regardless from where it is used
export function PageHeader({ autogenerateBreadcrumbs = false, ...headerProps }: IPageHeaderContentBasicProps) {
    const PageHeader = autogenerateBreadcrumbs ? PageHeaderContentWithBreadCrumbs : PageHeaderContent;

    return (
        <PageHeaderPortal>
            <PageHeader {...headerProps} />
        </PageHeaderPortal>
    );
}

function PageHeaderPortal({ children }: any) {
    // The portal target is the header slot rendered by <Header/> (persistent in AppLayout, so it
    // already exists by the time any page mounts). Resolve it in an effect rather than during render
    // and let React own the portalled children.
    //
    // The previous implementation imperatively cleared the slot (`innerHTML = ""`) before enabling a
    // one-shot portal. That wipe removed nodes React still believed it managed: when navigating
    // between detail pages the incoming page's portal could clear the outgoing page's not-yet-
    // unmounted header, desyncing React's tree and leaving the slot empty (observed as missing
    // breadcrumbs on the heavier workflow page). Letting React mount/unmount the portal children
    // removes that race — React cleans up the old page's header on unmount on its own.
    const [portalTarget, setPortalTarget] = useState<HTMLElement | null>(null);

    useEffect(() => {
        setPortalTarget(document.getElementById(APP_VIEWHEADER_ID));
    }, []);

    return portalTarget ? ReactDOM.createPortal(<>{children}</>, portalTarget) : null;
}

function PageHeaderContent({
    type,
    pluginId,
    alternateDepiction,
    breadcrumbs,
    breadcrumbsExtensions,
    pageTitle,
    autogeneratePageTitle = false,
    actionsMenu,
}: IPageHeaderContentBasicProps) {
    const dispatch = useDispatch<AppDispatch>();

    const handleBreadcrumbItemClick = React.useCallback((itemUrl, e) => {
        e.preventDefault();
        if (itemUrl) {
            dispatch(routerOp.goToPage(itemUrl, {}));
        }
    }, []);

    const generatedPageTitle =
        autogeneratePageTitle && breadcrumbs && breadcrumbs.length > 0
            ? (breadcrumbs[breadcrumbs.length - 1].text ?? "").toString()
            : "";

    const renderWindowTitle = () => {
        const typeinfo = !!type ? `(${type})` : "";
        const position =
            !!breadcrumbs && breadcrumbs.length > 1
                ? "at " +
                  breadcrumbs
                      .slice(0, breadcrumbs.length - 1)
                      .map((o) => o.text)
                      .join(" / ")
                : "";
        const brandingSuffix =
            APPLICATION_CORPORATION_NAME() || APPLICATION_SUITE_NAME()
                ? ` — ${APPLICATION_CORPORATION_NAME()} ${APPLICATION_SUITE_NAME()}`
                : "";

        return `${pageTitle || generatedPageTitle} ${typeinfo} ${position}${brandingSuffix}`;
    };

    const displayedTitle = pageTitle || generatedPageTitle;
    // single-row header line: the page title is the trail's current (last) item, never a link.
    // `BreadcrumbList` renders the last item in the "current page" treatment automatically.
    const allBreadcrumbs = (breadcrumbs ?? []).concat(breadcrumbsExtensions ?? []);
    const trailWithCurrentPage =
        displayedTitle &&
        (allBreadcrumbs.length === 0 ||
            (allBreadcrumbs[allBreadcrumbs.length - 1].text ?? "").toString() !== displayedTitle)
            ? allBreadcrumbs.concat([{ text: displayedTitle }])
            : allBreadcrumbs;

    return (
        <>
            <Helmet title={renderWindowTitle()} />
            <OverviewItem>
                {(!!type || !!alternateDepiction) && (
                    <OverviewItemDepiction data-test-id="page-header-depiction">
                        {!!type ? (
                            <ItemDepiction itemType={type} pluginId={pluginId} size={{ small: true }} />
                        ) : (
                            <Icon name={[alternateDepiction!]} small />
                        )}
                    </OverviewItemDepiction>
                )}
                <OverviewItemDescription>
                    {trailWithCurrentPage.length > 0 && (
                        <OverviewItemLine>
                            {/* keep an h1 for the document outline; visually the current
                                breadcrumb item represents the page title */}
                            <h1 className="sr-only">{displayedTitle}</h1>
                            <BreadcrumbList items={trailWithCurrentPage} onItemClick={handleBreadcrumbItemClick} />
                        </OverviewItemLine>
                    )}
                </OverviewItemDescription>
                {!!actionsMenu && <OverviewItemActions>{actionsMenu}</OverviewItemActions>}
            </OverviewItem>
        </>
    );
}

const PageHeaderContentWithBreadCrumbs = fetchBreadcrumbs(PageHeaderContent);

// Custom hook to update single properties of the element
export function usePageHeader({ ...propsHeader }: IPageHeaderContentBasicProps) {
    const [pageHeaderProps, setPageHeaderProps] = useState<IPageHeaderContentBasicProps>({ ...propsHeader });

    const updatePageHeader = (propsUpdate: IPageHeaderContentBasicProps) => {
        setPageHeaderProps({ ...pageHeaderProps, ...propsUpdate });
    };

    const pageHeader = <PageHeader {...pageHeaderProps} />;
    return {
        pageHeader,
        updateType: (itemType: string, pluginId?: string) => {
            updatePageHeader({ type: itemType, pluginId });
        },
        updatePageTitle: (update) => {
            updatePageHeader({ pageTitle: update, autogeneratePageTitle: false });
        },
        updateBreadcrumbs: (update) => {
            updatePageHeader({ breadcrumbs: update, autogenerateBreadcrumbs: false });
        },
        updateBreadcrumbsExtensions: (update) => {
            updatePageHeader({ breadcrumbsExtensions: update, autogenerateBreadcrumbs: true });
        },
        updateActionsMenu: (update: React.JSX.Element) => {
            updatePageHeader({ actionsMenu: update });
        },
        updatePageHeader,
    } as const;
}
